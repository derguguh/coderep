#ifndef BACKEND_LUA_TOKEN_H
#define BACKEND_LUA_TOKEN_H

#include <stddef.h>
#include <stdio.h>

enum lua_token_type {
	TOKEN_TYPE_INVALID,
	TOKEN_TYPE_EOF,
	TOKEN_TYPE_IDENTIFIER,
	TOKEN_TYPE_STRING,
	TOKEN_TYPE_MULTI_LINE_STRING,
	// Numbers
	TOKEN_TYPE_LIT_INTEGER,
	TOKEN_TYPE_LIT_DECIMAL,
	TOKEN_TYPE_LIT_HEX,
	TOKEN_TYPE_LIT_SCIENTIFIC,
	// Keywords
	TOKEN_TYPE_KW_AND,
	TOKEN_TYPE_KW_BREAK,
	TOKEN_TYPE_KW_DO,
	TOKEN_TYPE_KW_ELSE,
	TOKEN_TYPE_KW_ELSEIF,
	TOKEN_TYPE_KW_END,
	TOKEN_TYPE_KW_FALSE,
	TOKEN_TYPE_KW_FOR,
	TOKEN_TYPE_KW_FUNCTION,
	TOKEN_TYPE_KW_GOTO,
	TOKEN_TYPE_KW_IF,
	TOKEN_TYPE_KW_IN,
	TOKEN_TYPE_KW_LOCAL,
	TOKEN_TYPE_KW_NIL,
	TOKEN_TYPE_KW_NOT,
	TOKEN_TYPE_KW_OR,
	TOKEN_TYPE_KW_REPEAT,
	TOKEN_TYPE_KW_RETURN,
	TOKEN_TYPE_KW_THEN,
	TOKEN_TYPE_KW_TRUE,
	TOKEN_TYPE_KW_UNTIL,
	TOKEN_TYPE_KW_WHILE,
	// Characters
	TOKEN_TYPE_CHAR_PLUS,
	TOKEN_TYPE_CHAR_MINUS,
	TOKEN_TYPE_CHAR_MULT,
	TOKEN_TYPE_CHAR_MODULE,
	TOKEN_TYPE_CHAR_CARET,
	TOKEN_TYPE_CHAR_HASH,
	TOKEN_TYPE_CHAR_AMPERSAND,
	TOKEN_TYPE_CHAR_COMMA,
	TOKEN_TYPE_CHAR_SEMICOLON,
	TOKEN_TYPE_CHAR_VBAR,
	TOKEN_TYPE_CHAR_LPARENTHESIS,
	TOKEN_TYPE_CHAR_RPARENTHESIS,
	TOKEN_TYPE_CHAR_LBRACKET,
	TOKEN_TYPE_CHAR_RBRACKET,
	TOKEN_TYPE_CHAR_LBRACE,
	TOKEN_TYPE_CHAR_RBRACE,
	TOKEN_TYPE_CHAR_LESS_THAN,
	TOKEN_TYPE_CHAR_SHIFT_LEFT,
	TOKEN_TYPE_CHAR_LESS_OR_EQUALS_THAN,
	TOKEN_TYPE_CHAR_GREATER_THAN,
	TOKEN_TYPE_CHAR_SHIFT_RIGHT,
	TOKEN_TYPE_CHAR_GREATER_OR_EQUALS_THAN,
	TOKEN_TYPE_CHAR_COLON,
	TOKEN_TYPE_CHAR_DOUBLE_COLON,
	TOKEN_TYPE_CHAR_TILDE,
	TOKEN_TYPE_CHAR_NOT_EQUALS,
	TOKEN_TYPE_CHAR_SLASH,
	TOKEN_TYPE_CHAR_DOUBLE_SLASH,
	TOKEN_TYPE_CHAR_ASSIGN,
	TOKEN_TYPE_CHAR_EQUALS,
	TOKEN_TYPE_CHAR_ATTRIBUTION,
	TOKEN_TYPE_CHAR_PERIOD,
	TOKEN_TYPE_CHAR_CONCAT,
	TOKEN_TYPE_CHAR_EPSILON,
};

struct lua_token {
	enum lua_token_type type;
	size_t id;
};

static inline void lua_token_print(const struct lua_token self)
{
	printf("Token: { .type=%d, .id=%lu }\n", self.type, self.id);
}

#endif

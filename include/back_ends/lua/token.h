#ifndef BACK_END_LUA_TOKEN_H
#define BACK_END_LUA_TOKEN_H

#include <stddef.h>

enum token_type {
	TOKEN_TYPE_UNKNOWN = -2,
	TOKEN_TYPE_EOF,
	TOKEN_TYPE_IDENTIFIER,
	TOKEN_TYPE_STRING,
	// Numbers
	TOKEN_TYPE_INTEGER,
	TOKEN_TYPE_DECIMAL,
	TOKEN_TYPE_HEX,
	TOKEN_TYPE_SCIENTIFIC_NUMBER,
	// Keywords
	TOKEN_TYPE_AND,
	TOKEN_TYPE_BREAK,
	TOKEN_TYPE_DO,
	TOKEN_TYPE_ELSE,
	TOKEN_TYPE_ELSEIF,
	TOKEN_TYPE_END,
	TOKEN_TYPE_FALSE,
	TOKEN_TYPE_FOR,
	TOKEN_TYPE_FUNCTION,
	TOKEN_TYPE_GLOBAL,
	TOKEN_TYPE_GOTO,
	TOKEN_TYPE_IF,
	TOKEN_TYPE_IN,
	TOKEN_TYPE_LOCAL,
	TOKEN_TYPE_NIL,
	TOKEN_TYPE_NOT,
	TOKEN_TYPE_OR,
	TOKEN_TYPE_REPEAT,
	TOKEN_TYPE_RETURN,
	TOKEN_TYPE_THEN,
	TOKEN_TYPE_TRUE,
	TOKEN_TYPE_UNTIL,
	TOKEN_TYPE_WHILE,
};

struct token {
	enum token_type type;
	size_t id;
};

void token_print(const struct token self);

#endif

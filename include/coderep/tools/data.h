#ifndef CODEREP_TOOLS_DATA_H
#define CODEREP_TOOLS_DATA_H

#define DATA_TYPE(d) ((d) & 0xFF000000)
#define DATA_FLAGS(d) ((d) & 0x00FFFFFF)

enum data {
	// Types
	NONE			= 0x00000000,
	BRUTE			= 0x01000000,
	LIST			= 0x02000000,
	DISTRIBUTIVE		= 0x04000000,
	// Flags
	BRUTE_RAW		= 0x01000001,
	LIST_RAW		= 0x02000001,
	DISTRIBUTIVE_RAW	= 0x04000001,
	DISTRIBUTIVE_MIN	= 0x04000002,
	DISTRIBUTIVE_MAX	= 0x04000004,
	DISTRIBUTIVE_AVG	= 0x04000008,
	DISTRIBUTIVE_MODA	= 0x04000010,
	DISTRIBUTIVE_MEDIAN	= 0x04000020,
	DISTRIBUTIVE_FREQUENCY	= 0x04000040,
	DISTRIBUTIVE_VALUE	= 0x04000080,
	// Mixs
	DISTRIBUTIVE_DEFAULT	= 0x0400000E, // min, max and avg
	DISTRIBUTIVE_STATS	= 0x0400003E, // min, max, avg, moda and median
	DISTRIBUTIVE_LIST	= 0x040000C0, // frequency and value
	DISTRIBUTIVE_ALL	= 0x040000FF,
};

#endif

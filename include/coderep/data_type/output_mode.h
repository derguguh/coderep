#ifndef CODEREP_DATA_TYPE_OUTPUT_H
#define CODEREP_DATA_TYPE_OUTPUT_H

enum output_mode {
	// Flags
	OUTPUT_MODE_NONE		= 0x00000000,
	OUTPUT_MODE_RAW			= 0x00000001,
	OUTPUT_MODE_MIN			= 0x00000002,
	OUTPUT_MODE_AVG			= 0x00000004,
	OUTPUT_MODE_MAX			= 0x00000008,
	OUTPUT_MODE_MODE		= 0x00000010,
	OUTPUT_MODE_MEDIAN		= 0x00000020,
	OUTPUT_MODE_VALUE		= 0x00000040,
	OUTPUT_MODE_FREQUENCY		= 0x00000080,
	OUTPUT_MODE_COUNT		= 0x00000100,
	// Flag mixes
	OUTPUT_MIX_DISTRIBUTION		= 0x000000C0,
	OUTPUT_MIX_STATS		= 0x0000003E,
	OUTPUT_MIX_ALL			= 0xFFFFFFFF,
	OUTPUT_DEFAULT_FREQUENCY	= OUTPUT_MIX_STATS | OUTPUT_MODE_COUNT,
	OUTPUT_DEFAULT_STATISTIC	= OUTPUT_MIX_STATS | OUTPUT_MODE_VALUE,
	OUTPUT_DEFAULT_BRUTE		= OUTPUT_MODE_VALUE,
};

#endif
